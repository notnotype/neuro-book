/**
 * edit 工具（docs/specs/harness/builtin-tools.md 输出 6）：OMP hashline 编辑引擎的装配与落盘。头里的路径是资源地址。
 * 语义（标签核对、未展示行守卫、陈旧标签重映射、模糊匹配）全部交给引擎；带方案的头由引擎经 `resolveUrl` 回调问本模块要真实路径，
 * 引擎决定要写什么之后，每个绝对路径再按本次打开过的提供者反查方案、转回相对路径经提供者写。
 */

import {editDescription, EditSession} from "@oh-my-pi/pi-natives";
import type {EditPolicy, EditUrlResolution, EditWriteRequest, EditWriteResponse} from "@oh-my-pi/pi-natives";
import Type from "typebox";
import {defineTool} from "../tools/tools";
import type {ToolDefinition, ToolOutcome} from "../tools/tools";
import {describeSchemes, openAddress} from "./read";
import type {DirectoryProvider, FilesFailure, ResourceAccess, SchemeContext, SnapshotStores} from "./types";

/** hashline 的文件头：`[地址#TAG]`；多文件编辑有多个头。 */
const HEADER = /^\[(.+)#[0-9A-Fa-f]{4}\]\s*$/u;

const EditParameters = Type.Object({
    input: Type.String({minLength: 1, description: "hashline 原文：首行 [方案://路径#tag]，之后是行锚操作"}),
});

/**
 * 写入失败只在本模块内抛出。原生引擎会把 writer 抛出的异常吞成 outcome.isError，JS 的异常对象到不了 apply 外面，
 * 所以失败同时记在 WriteLog 里，apply 返回后据它构造结果。
 */
class WriteFailed extends Error {
    constructor(readonly code: FilesFailure, readonly detail: string) {
        super(detail);
        this.name = "WriteFailed";
    }
}
type WriteLog = {failure: {code: FilesFailure; detail: string} | null; written: string[]};

/** 引擎给的是绝对路径；转回根内相对路径交给提供者，不在根内的为 null。 */
function relativeToRoot(root: string, absolute: string): string | null {
    const base = root.endsWith("/") ? root : `${root}/`;
    if (absolute === root) return null;
    return absolute.startsWith(base) ? absolute.slice(base.length) : null;
}

type Target = {scheme: string; provider: DirectoryProvider; path: string; absolute: string; address: string};
type TargetResult = {ok: true; value: Target} | {ok: false; code: FilesFailure; message: string};

export function editTool(input: {resources: ResourceAccess; stores: SnapshotStores}): ToolDefinition {
    const policy: EditPolicy = {
        // 头全是带方案的地址，引擎不会按 cwd、homeDir 解析任何头；给根只是让字段有值
        cwd: "/",
        mode: "hashline",
        allowFuzzy: true,
        fuzzyThreshold: 0.8,
        enforceSeenLines: true,
        blockAutoGenerated: true,
        planActive: false,
        urlSchemes: input.resources.schemes().map((item) => item.scheme),
        urlAliasSchemes: [],
        planWritableRoots: [],
        homeDir: "/",
        rawInput: false,
    };

    /** 地址 → 可写的目录型提供者与真实绝对路径；虚拟或只读方案、越界、不存在的方案各给自己的码。 */
    const resolveTarget = async (raw: string, context: SchemeContext): Promise<TargetResult> => {
        // 引擎会去掉头里路径的前后空白：这样的头本模块不替它猜
        if (raw !== raw.trim()) return {ok: false, code: "invalid-address", message: `头里的地址带前后空白：${raw}`};
        const opened = openAddress(input.resources, raw, context);
        if (!opened.ok) return {ok: false, code: opened.code, message: opened.detail};
        const {provider, path, address} = opened.value;
        if (provider.kind !== "directory") return {ok: false, code: "read-only", message: `${address} 是虚拟方案的资源，只能 read，不能 edit`};
        if (provider.readonly) return {ok: false, code: "read-only", message: `${address} 所在的方案只读`};
        // 引擎会自己读头里的文件来核对标签、并把内容回显在错误里，所以根外的路径要在交给引擎之前按真实路径拦下
        const located = await provider.locate(path);
        if (!located.ok) return {ok: false, code: located.code, message: located.detail};
        return {ok: true, value: {scheme: address.slice(0, address.indexOf("://")), provider, path, absolute: located.value, address}};
    };

    return defineTool({
        id: "edit",
        // 语法说明照 OMP（模型按它训练过），后面加本模块的约束
        description: `${editDescription("hashline")}\n\n<harness>\n路径是资源地址 方案://路径（可用方案：${describeSchemes(input.resources)}），不能是裸路径、绝对路径或 ~。[地址#tag] 头只能来自本会话 read 的输出，只能改 read 展示过的行；只读方案与虚拟方案（没有标签头的）不能改。这里没有 write 与 search 工具：新建文件不在本工具范围内，内容要先 read。\n</harness>`,
        parameters: EditParameters,
        risk: "write",
        async execute(args, context): Promise<ToolOutcome> {
            const {input: text} = args as {input: string};
            const targets = new Map<string, Target>();
            for (const line of text.split("\n")) {
                const match = HEADER.exec(line);
                if (match === null) continue;
                const target = await resolveTarget(match[1]!, {sessionId: context.session.id});
                if (!target.ok) return {ok: false, code: target.code, message: target.message};
                targets.set(target.value.absolute, target.value);
            }
            /** 引擎给的绝对路径 → 本次打开过的提供者与它眼里的相对路径。 */
            const ownerOf = (absolute: string): {target: Target; path: string} | null => {
                for (const target of targets.values()) {
                    const path = relativeToRoot(target.provider.root, absolute);
                    if (path !== null) return {target, path};
                }
                return null;
            };
            const addressOf = (absolute: string): string => {
                const owner = ownerOf(absolute);
                return owner === null ? absolute : `${owner.target.scheme}://${owner.path}`;
            };
            const writer = async (log: WriteLog, request: EditWriteRequest): Promise<EditWriteResponse> => {
                const owner = ownerOf(request.path);
                if (owner === null) throw new WriteFailed("outside-root", `引擎要写的路径不在任何已打开方案的根内：${request.displayPath}`);
                const {provider} = owner.target;
                const checked = provider.resolve(owner.path);
                if (!checked.ok) throw new WriteFailed(checked.code, checked.detail);
                // 访问层自己的码要留住（例如悬空链接的 outside-root）；只有真正的 I/O 失败才是 io-failed
                const failed = (where: string, result: {code: FilesFailure; detail: string}): WriteFailed => new WriteFailed(result.code === "io-failed" ? "io-failed" : result.code, `${where}：${result.detail}`);
                const written = (path: string): void => void log.written.push(`${owner.target.scheme}://${path}`);
                if (request.content === undefined) {
                    const removed = await provider.remove(owner.path);
                    if (!removed.ok && removed.code !== "not-found") throw failed(request.displayPath, removed);
                    written(owner.path);
                    return {written: ""};
                }
                if (request.moveTo !== undefined) {
                    const destination = ownerOf(request.moveTo);
                    if (destination === null) throw new WriteFailed("outside-root", `引擎要移到的路径不在任何已打开方案的根内：${request.moveTo}`);
                    const moved = await destination.target.provider.write(destination.path, request.content);
                    if (!moved.ok) throw failed(request.moveTo, moved);
                    log.written.push(`${destination.target.scheme}://${destination.path}`);
                    const removed = await provider.remove(owner.path);
                    if (!removed.ok && removed.code !== "not-found") throw failed(request.displayPath, removed);
                    written(owner.path);
                    return {written: request.content};
                }
                const result = await provider.write(owner.path, request.content);
                if (!result.ok) throw failed(request.displayPath, result);
                written(owner.path);
                return {written: request.content};
            };
            const resolveUrl = async (error: Error | null, url: string): Promise<EditUrlResolution> => {
                if (error !== null) throw error;
                const target = await resolveTarget(url, {sessionId: context.session.id});
                return target.ok ? {path: target.value.absolute, planWritable: false} : {error: target.message, planWritable: false};
            };
            const session = new EditSession(input.stores.forSession(context.session.id), policy, undefined, resolveUrl);
            const log: WriteLog = {failure: null, written: []};
            try {
                session.setArgsJson(JSON.stringify({input: text}));
                session.finish();
                const outcome = await session.apply({lspFlush: false}, async (error, request) => {
                    if (error !== null) throw error;
                    try {
                        return await writer(log, request);
                    } catch (failure) {
                        if (failure instanceof WriteFailed) log.failure ??= {code: failure.code, detail: failure.detail};
                        throw failure;
                    }
                });
                if (log.failure !== null) return {ok: false, code: log.failure.code, message: log.failure.detail, details: {written: log.written}};
                const files = outcome.files.map((file) => ({path: addressOf(file.path), op: file.op, warnings: [...file.warnings]}));
                if (outcome.isError) return {ok: false, code: "edit-rejected", message: outcome.text, details: {files}};
                return {ok: true, content: outcome.text, details: {files}};
            } catch (error) {
                if (log.failure !== null) return {ok: false, code: log.failure.code, message: log.failure.detail, details: {written: log.written}};
                return {ok: false, code: "edit-rejected", message: error instanceof Error ? error.message : String(error)};
            } finally {
                session.close();
            }
        },
    });
}
